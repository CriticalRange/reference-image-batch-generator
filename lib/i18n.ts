function applyI18nResources() {
  for (const [lng, bundle] of Object.entries(resources)) {
    i18n.addResourceBundle(lng, 'translation', bundle.translation, true, true);
  }
}

if (!i18n.isInitialized) {
  void i18n
    .use(initReactI18next)
    .init({
      resources,
      lng: 'tr',
      fallbackLng: 'tr',
      interpolation: {
        escapeValue: false
      },
      returnNull: false,
      // Prefer fallback language text over the raw key name when a key is missing.
      parseMissingKeyHandler: (key) => key
    })
    .then(() => {
      applyI18nResources();
    });
} else {
  // HMR / re-import: merge latest keys into the already-running i18n instance.
  applyI18nResources();
}

